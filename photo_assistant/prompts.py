def character_name_for(sprite_catalog: Path) -> str:
    path = Path(sprite_catalog).resolve()
    if path == WHITE_DRAGON_CATALOG.resolve():
        return "小白龙"
    return "Vita" if path == DEFAULT_SPRITE_CATALOG.resolve() else path.stem


